"""Locate and check private derived inputs without granting Build admission.

The saved transfer and existing publisher still authorize every generated byte.
Paths are derived from the selected candidate; no arbitrary include root is
accepted. These checks detect substitution at observation boundaries, not
exclusive ownership against another process running as the same user.
"""
from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path
import re
import secrets

from lyra_output_paths import is_private_generation

LEGACY_OUTPUT = Path('Data/Generated/lyra_project')
PRIVATE_DIRECTORY = 'generated-inputs'
INCLUDE_PREFIX = '!LYRA_GENERATED_ROOT/'


def _canonical(path):
    path = Path(path)
    if (not path.is_absolute() or path != path.resolve()
            or any(p.is_symlink() for p in (path, *path.parents))):
        raise ValueError('LYRA_GENERATED_PATH: canonical paths without symlinks required')
    return path


def private_folder(root, project, candidate):
    root, project, candidate = map(_canonical, (root, project, candidate))
    if not is_private_generation(project, root, candidate):
        raise ValueError('LYRA_GENERATED_PATH: private project generation required')
    folder = _canonical(candidate.parent / PRIVATE_DIRECTORY)
    # The value is substituted inside an Asar quoted string. Fail closed for
    # metacharacters rather than guessing either shell or assembler escaping.
    if any(ord(c) < 32 or ord(c) == 127 or c in "\"'!;{}\\" for c in str(folder)):
        raise ValueError('LYRA_GENERATED_PATH: unsupported Asar path characters')
    return folder


def selected_folder(root, environment=None):
    env = os.environ if environment is None else environment
    candidate = env.get('OOS_LYRA_CANDIDATE', '')
    if not candidate:
        return Path(root) / LEGACY_OUTPUT
    project = env.get('OOS_LYRA_PROJECT', '')
    if not project:
        raise ValueError('LYRA_GENERATED_PATH: candidate requires project')
    return private_folder(root, project, candidate)


def validate_prepared(folder):
    """Check every emitted file, including incbin payloads, twice around reads."""
    folder = _canonical(folder)
    marker = _canonical(folder / 'prepare.json')
    before = marker.read_bytes()
    prepared = json.loads(before)
    hashes = prepared.get('generated_files')
    if type(hashes) is not dict or not hashes:
        raise ValueError('LYRA_GENERATED_IDENTITY: generated file hashes required')
    observed = {}
    for name, digest in hashes.items():
        if (not isinstance(name, str) or not name or '\\' in name
                or Path(name).is_absolute() or any(p in ('', '.', '..') for p in name.split('/'))
                or name == 'prepare.json' or not isinstance(digest, str)
                or re.fullmatch('[0-9a-f]{64}', digest) is None):
            raise ValueError('LYRA_GENERATED_IDENTITY: invalid generated file binding')
        path = _canonical(folder / name)
        raw = path.read_bytes()
        if hashlib.sha256(raw).hexdigest() != digest:
            raise ValueError(f'LYRA_GENERATED_IDENTITY: generated bytes changed: {name}')
        observed[path] = raw
    for path, raw in observed.items():
        if _canonical(path).read_bytes() != raw:
            raise ValueError('LYRA_GENERATED_IDENTITY: generated bytes changed during scan')
    if _canonical(marker).read_bytes() != before:
        raise ValueError('LYRA_GENERATED_IDENTITY: preparation changed during scan')
    return prepared


def write_private_outputs(folder, files):
    """Write through directory descriptors; path replacement cannot redirect writes.

    There is deliberately no check-then-write fallback on platforms lacking
    these APIs. Reading these files later still needs the Build ownership and
    source/receipt checks; this routine does not grant that authority.
    """
    required = (os.open, os.mkdir, os.unlink, os.rename)
    if (not hasattr(os, 'O_NOFOLLOW') or not hasattr(os, 'O_DIRECTORY')
            or any(call not in os.supports_dir_fd for call in required)):
        raise ValueError('LYRA_GENERATED_PLATFORM: anchored private writer unavailable')
    folder = _canonical(folder)
    if folder.exists():
        raise ValueError('LYRA_GENERATED_EXISTS: use a fresh generation')
    if 'prepare.json' not in files:
        raise ValueError('LYRA_GENERATED_IDENTITY: preparation marker required')
    for name in files:
        if (not isinstance(name, str) or not name or '\\' in name
                or Path(name).is_absolute() or any(p in ('', '.', '..') for p in name.split('/'))):
            raise ValueError('LYRA_GENERATED_IDENTITY: invalid generated file name')
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
    parent_fd = os.open(folder.anchor, flags)
    output_fd = None
    try:
        for part in folder.parent.parts[1:]:
            next_fd = os.open(part, flags, dir_fd=parent_fd)
            os.close(parent_fd)
            parent_fd = next_fd
        os.mkdir(folder.name, mode=0o700, dir_fd=parent_fd)
        output_fd = os.open(folder.name, flags, dir_fd=parent_fd)
        identity = os.fstat(output_fd)

        def check_directory():
            actual = _canonical(folder).stat(follow_symlinks=False)
            if (actual.st_dev, actual.st_ino) != (identity.st_dev, identity.st_ino):
                raise ValueError('LYRA_GENERATED_PATH: generated directory changed during write')

        for name in [key for key in files if key != 'prepare.json'] + ['prepare.json']:
            check_directory()
            parts = Path(name).parts
            directory_fd = os.dup(output_fd)
            temporary = None
            try:
                for part in parts[:-1]:
                    try:
                        os.mkdir(part, mode=0o700, dir_fd=directory_fd)
                    except FileExistsError:
                        pass
                    next_fd = os.open(part, flags, dir_fd=directory_fd)
                    os.close(directory_fd)
                    directory_fd = next_fd
                temporary = '.lyra-' + secrets.token_hex(16)
                fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW,
                             0o600, dir_fd=directory_fd)
                with os.fdopen(fd, 'wb') as handle:
                    handle.write(files[name])
                os.rename(temporary, parts[-1], src_dir_fd=directory_fd, dst_dir_fd=directory_fd)
                temporary = None
            finally:
                if temporary is not None:
                    os.unlink(temporary, dir_fd=directory_fd)
                os.close(directory_fd)
        check_directory()
        validate_prepared(folder)
        check_directory()
    except BaseException:
        if output_fd is not None:
            try:
                os.unlink('prepare.json', dir_fd=output_fd)
            except FileNotFoundError:
                pass
        raise
    finally:
        if output_fd is not None:
            os.close(output_fd)
        os.close(parent_fd)


def source_path(path, root):
    """Keep actual external paths in metadata; never attribute them to the engine."""
    root, path = Path(root).resolve(), Path(path)
    if path.is_relative_to(root):
        return path.relative_to(root)
    folder = selected_folder(root)
    if folder == root / LEGACY_OUTPUT or not path.is_relative_to(folder):
        raise ValueError(f'ASM source is outside repo root: {path}')
    prepared = validate_prepared(folder)
    if path.relative_to(folder).as_posix() not in prepared['generated_files']:
        raise ValueError(f'ASM source is not a bound generated input: {path}')
    return path


def main():
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('command', choices=('path', 'verify'))
    parser.add_argument('--root', type=Path, required=True)
    args = parser.parse_args()
    folder = selected_folder(args.root)
    if args.command == 'verify':
        validate_prepared(folder)
    else:
        print(folder.as_posix())


if __name__ == '__main__':
    main()
