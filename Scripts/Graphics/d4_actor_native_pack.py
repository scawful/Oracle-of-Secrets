#!/usr/bin/env python3
"""Pack reviewed D4 actor designs into unbound native sprite art candidates.

No ROM writer, global sheet assignment or hardware palette assignment. The
approved warden is traced from its large concept cells; derived poses use only
integer translation of the native art. Protector front/side source is the
existing native translation, not the rejected prototype artwork.
"""
from pathlib import Path
import argparse, collections, hashlib, json, sys
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'Scripts/Generate'))
import sheet_codec, lz2
from sheet_table import decomp,ptr

CONCEPT_SHA='3d8e3e74f21de3008056d1f07bfeb5b69285787aa662d757bd61fa5fa4deeb45'
BASE_SHA='8d6157840e402f98d5c4b1d61da90be072531fa661bc1608ae0eeab1b898e721'
LINK_SHA='be940d91dbc82623011124f5fb7cd267b9b4334b5c31e7b853b3fa66151728d6'
PROTECTOR_HEAD=[0,0x0C63,0x2525,0x39E5,0x46F0,0x2F7D,0x5B7D,0x1ADF]
PROTECTOR_BODY=PROTECTOR_HEAD.copy();PROTECTOR_BODY[5]=0x1970
ARMOR=[0,0x0C63,0x0CCA,0x1172,0x229B,0x3AB7,0x5BBE,0x18D2]
IRON=[0,0x0C63,0x2929,0x4E73,0x0CCA,0x1172,0x3AB7,0x5BBE]
PALETTES={'protector_head':PROTECTOR_HEAD,'protector_body':PROTECTOR_BODY,
          'warden_armor':ARMOR,'warden_iron':IRON}
RESERVED={0x20,0x22,0xC0,0xC2,0xE0,0xE2}
PALETTE_ROWS={'protector_head':3,'protector_body':4,'warden_armor':5,'warden_iron':6}

def rgb(w):return tuple(((w>>s)&31)*255//31 for s in (0,5,10))

def trace_warden(image,x0):
    # Flood only background connected to the crop border. Neutral iron and
    # ivory highlights inside a dark outline must never be erased as grey BG.
    x0,y0,dx,dy=x0,650,7,7;w,h=224,280
    allowed=set()
    for y in range(h):
        for x in range(w):
            colour=image.getpixel((x0+x,y0+y))
            if max(colour)-min(colour)<18 and min(colour)>70:allowed.add((x,y))
    queue=collections.deque(p for p in allowed if p[0] in (0,w-1) or p[1] in (0,h-1))
    background=set(queue)
    while queue:
        x,y=queue.popleft()
        for n in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
            if n in allowed and n not in background:background.add(n);queue.append(n)
    roles=[rgb(w) for w in ARMOR]+[rgb(IRON[2]),rgb(IRON[3])]
    grid=[[0]*32 for _ in range(48)]
    for y in range(40):
        for x in range(32):
            sx,sy=x*dx+3,y*dy+3
            if (sx,sy) in background:continue
            c=image.getpixel((x0+sx,y0+sy))
            grid[y+4][x]=min(range(1,10),key=lambda i:sum((a-b)**2 for a,b in zip(c,roles[i])))
    return grid

def translate_band(grid,top,bottom,dx,dy):
    result=[r.copy() for r in grid]
    for y in range(top,bottom):result[y]=[0]*len(grid[0])
    for y in range(top,bottom):
        for x,v in enumerate(grid[y]):
            if v and 0<=x+dx<len(grid[0]) and 0<=y+dy<len(grid):result[y+dy][x+dx]=v
    return result

def protector_roles(path):
    rows=path.read_text().splitlines();assert len(rows)==24 and all(len(r)==16 for r in rows)
    return [[0 if c=='.' else int(c) for c in row] for row in rows]

def rgba_for_roles(grid,kind):
    w,h=len(grid[0]),len(grid);im=Image.new('RGBA',(w,h))
    palette=([*ARMOR,IRON[2],IRON[3]] if kind=='warden' else [*PROTECTOR_HEAD,PROTECTOR_BODY[5]])
    for y,row in enumerate(grid):
        for x,v in enumerate(row):
            if v:im.putpixel((x,y),rgb(palette[v])+(255,))
    return im

def tiles_for_warden(grid):
    result=[]
    for palette in ('warden_armor','warden_iron'):
        for y0 in range(0,48,16):
            for x0 in range(0,32,16):
                tile=[[0]*16 for _ in range(16)]
                for y in range(16):
                    for x in range(16):
                        v=grid[y0+y][x0+x]
                        if palette=='warden_armor' and 1<=v<=7:tile[y][x]=v
                        if palette=='warden_iron' and v in (8,9):tile[y][x]=v-6
                if any(v for r in tile for v in r):result.append(dict(x=x0,y=y0,palette=palette,tile=tile))
    return result

def tiles_for_protector(grid):
    head=[[0]*16 for _ in range(16)];body=[[0]*16 for _ in range(16)]
    for y,row in enumerate(grid):
        for x,v in enumerate(row):
            if not v:continue
            if y<14 and v!=8:head[y][x]=v
            if y>=8 and v!=5:body[y-8][x]=5 if v==8 else v
            assert not(v==8 and y<8)
            assert not(v==5 and y>=14)
    return [dict(x=0,y=0,palette='protector_head',tile=head),dict(x=0,y=8,palette='protector_body',tile=body)]

def emit_binding(out,report):
    """Emit reviewable source inputs, without copying them into the checkout."""
    binding=out/'binding';binding.mkdir()
    lines=['; GENERATED by Scripts/Graphics/d4_actor_native_pack.py.',
           '; Accepted native actor pack; private D4 flag only. OBJ colours 1..7.',
           '; Logical palettes use hardware rows 3,4,5,6; row 1 and row 7 unchanged.']
    starts=[];counts=[];entries=[]
    for i,(name,frame) in enumerate(report['frames'].items()):
        lines.append(f'!D4Zora_Frame_{name} = {i}')
        starts.append(len(entries));counts.append(len(frame['oam']))
        x0,y0=(-16,-40) if name.startswith('warden') else (-8,-16)
        entries.extend(dict(char=e['char'],x=e['x']+x0,y=e['y']+y0,
                            props=0x31 | (PALETTE_ROWS[e['palette']]<<1)) for e in frame['oam'])
    assert len(entries)<128, '16-bit coordinate offsets must fit 8-bit X'
    for label,values in [('FrameStarts',starts),('FrameCounts',counts),
                         ('Chars',[e['char'] for e in entries]),('Props',[e['props'] for e in entries])]:
        lines.extend([f'D4Zora_{label}:','  db '+', '.join(f'${v:02X}' for v in values)])
    for label,key in [('XOffsets','x'),('YOffsets','y')]:
        lines.extend([f'D4Zora_{label}:','  dw '+', '.join(str(e[key]) for e in entries)])
    for name,palette in PALETTES.items():
        lines.extend([f'D4Zora_Palette_{name}:','  dw '+', '.join(f'${v:04X}' for v in palette[1:])])
    (binding/'frames.asm').write_text('\n'.join(lines)+'\n')
    spec=json.loads((ROOT/'Data/graphics/source_sprite_sheets.json').read_text())
    spec['schema_version']=2
    for page,sheet in enumerate(report['sheets']):
        global_id=0xDF+page
        (binding/f'atlas-{global_id:02X}.txt').write_bytes((out/f'actor-page-{page}.txt').read_bytes())
        spec['sheets'].append(dict(global_sheet=f'0x{global_id:02X}',source=f'd4_zora/atlas-{global_id:02X}.txt',
                                   decoded_sha256=sheet['sha256'],why='Accepted D4 River protector and bronze pirate warden; Princess source cells and Baby upload slots preserved.'))
    (binding/'d4_zora_sprite_sheets.json').write_text(json.dumps(spec,indent=2)+'\n')
    report['binding']=dict(palette_rows=PALETTE_ROWS,colour_indices=[1,7],spriteset='4F',
                           sprite_relative_sheets=['6C','6D','6E','6F'],global_sheets=['DF','E0','E1','E2'],
                           asm_entries=len(entries),source_installed=False)

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--concept',type=Path,required=True)
    ap.add_argument('--protector',type=Path,required=True)
    ap.add_argument('--base-rom',type=Path,required=True)
    ap.add_argument('--link-reference',type=Path,required=True)
    ap.add_argument('--emit-binding',action='store_true',help='emit private-room source inputs after visual acceptance')
    ap.add_argument('--output',type=Path,required=True)
    args=ap.parse_args();out=args.output;assert not out.exists(),'fresh output required'
    raw=args.concept.read_bytes();assert hashlib.sha256(raw).hexdigest()==CONCEPT_SHA
    base=args.base_rom.read_bytes();assert hashlib.sha256(base).hexdigest()==BASE_SHA
    assert hashlib.sha256(args.link_reference.read_bytes()).hexdigest()==LINK_SHA
    image=Image.open(args.concept).convert('RGB');assert image.size==(1536,1024)
    front=trace_warden(image,736);side=trace_warden(image,1048)
    brace=translate_band(front,0,32,0,1)
    charge=translate_band(side,0,32,-1,0)
    vent=translate_band(front,0,28,0,1)
    # Brief native steam pixels use the existing ivory role, above the hose.
    for x,y in ((26,2),(27,2),(25,3),(26,3),(27,4)):vent[y][x]=6
    pfront=protector_roles(args.protector/'front-roles.txt')
    pside=protector_roles(args.protector/'side-roles.txt')
    # Rest lowers the head one pixel; healing returns to the selected idle pose.
    prest=translate_band(pfront,0,14,0,1)
    # Keep the fin and strap palette split valid after the simple head movement.
    for y,row in enumerate(prest):
        for x,v in enumerate(row):
            if v==8 and y<8:row[x]=1
            if v==5 and y>=14:row[x]=7
    frames={'warden_idle_front':('warden',front),'warden_idle_side':('warden',side),
            'warden_brace':('warden',brace),'warden_charge':('warden',charge),'warden_vent':('warden',vent),
            'protector_idle_front':('protector',pfront),'protector_idle_side':('protector',pside),
            'protector_rest':('protector',prest),'protector_healing':('protector',pfront)}
    sheets=[[[0]*128 for _ in range(32)] for _ in range(4)]
    # Preserve all Princess source cells exactly; Baby upload cells stay reserved.
    decoded,_=decomp(base,ptr(base,0x56+0x73));princess=sheet_codec.sheet_to_grid(decoded)
    for t in [*range(4),*range(16,20),*range(32,36),*range(48,52)]:
        x,y=(t%16)*8,(t//16)*8
        for yy in range(8):sheets[3][y+yy][x:x+8]=princess[y+yy][x:x+8]
    cells=[q+r+x for q in (0,0x40,0x80,0xC0) for r in (0,0x20) for x in range(0,16,2) if q+r+x not in RESERVED]
    allocated={};cursor=0;frame_data={};previews={}
    out.mkdir(parents=True)
    for name,(kind,grid) in frames.items():
        tiles=tiles_for_warden(grid) if kind=='warden' else tiles_for_protector(grid)
        entries=[]
        for piece in tiles:
            tile=piece.pop('tile');key=bytes(v for row in tile for v in row)
            assert all(v<=7 for v in key)
            if key not in allocated:
                assert cursor<len(cells),'actor art exceeds reserved atlas capacity'
                char=cells[cursor];cursor+=1;allocated[key]=char
                sheet=sheets[char>>6];t=char&63;x0,y0=(t%16)*8,(t//16)*8
                for y,row in enumerate(tile):sheet[y0+y][x0:x0+16]=row
            entries.append(dict(char=allocated[key],**piece))
        im=rgba_for_roles(grid,kind);im.save(out/(name+'-native.png'));previews[name]=im
        # Reconstruct every colour from the packed native OAM plan.
        actual=Image.new('RGBA',im.size)
        for entry in reversed(entries):
            char=entry['char'];sheet=sheets[char>>6];t=char&63;x0,y0=(t%16)*8,(t//16)*8
            palette=PALETTES[entry['palette']]
            for y in range(16):
                for x in range(16):
                    v=sheet[y0+y][x0+x]
                    if v and entry['x']+x<im.width and entry['y']+y<im.height:actual.putpixel((entry['x']+x,entry['y']+y),rgb(palette[v])+(255,))
        assert actual.tobytes()==im.tobytes(),name+' packed OAM composition differs'
        frame_data[name]=dict(canvas=list(im.size),oam=entries,composition_exact=True,
                              max_scanline_objects=max(sum(e['y']<=y<e['y']+16 for e in entries) for y in range(im.height)))
        (out/(name+'-roles.txt')).write_text('\n'.join(''.join('.' if not v else str(v) for v in row) for row in grid)+'\n')
    sheet_report=[]
    for i,grid in enumerate(sheets):
        raw=sheet_codec.grid_to_sheet(grid);assert sheet_codec.sheet_to_grid(raw)==grid
        text=sheet_codec.grid_to_text(grid);assert sheet_codec.text_to_grid(text)==grid
        compressed=lz2.compress(raw);assert lz2.decompress(compressed,max_output=1536)==(raw,len(compressed))
        stem=f'actor-page-{i}'
        (out/(stem+'.3bpp')).write_bytes(raw);(out/(stem+'.txt')).write_text(text);(out/(stem+'.lz2')).write_bytes(compressed)
        sheet_report.append(dict(page=i,decoded_bytes=len(raw),compressed_bytes=len(compressed),sha256=hashlib.sha256(raw).hexdigest()))
    for t in [*range(4),*range(16,20),*range(32,36),*range(48,52)]:
        x,y=(t%16)*8,(t//16)*8
        assert all(sheets[3][y+yy][x:x+8]==princess[y+yy][x:x+8] for yy in range(8))
    for c in (0x20,0x22):
        assert c not in allocated.values()
    for name,palette in PALETTES.items():(out/(name+'.pal')).write_bytes(b''.join(w.to_bytes(2,'little') for w in palette+[0]*8))
    font=ImageFont.truetype('/System/Library/Fonts/Supplemental/Arial.ttf',22)
    small=ImageFont.truetype('/System/Library/Fonts/Supplemental/Arial.ttf',16)
    board=Image.new('RGB',(1480,1100),'#252a2d');d=ImageDraw.Draw(board)
    d.text((24,15),'D4 ACTORS — native indexed frame candidates',font=font,fill='white')
    d.text((24,48),'Reviewed designs translated to native pixels. Palette rows and ROM binding remain unassigned.',font=small,fill='#c3d0c8')
    for col,name in enumerate(list(frames)[:5]):
        x=24+col*290;d.text((x,86),name.replace('warden_','').replace('_',' '),font=font,fill='white')
        im=previews[name];large=im.resize((im.width*5,im.height*5),Image.Resampling.NEAREST);board.paste(large,(x,126),large)
        board.paste(im,(x+190,316),im)
    d.text((24,418),'River protector',font=font,fill='white')
    for col,name in enumerate(list(frames)[5:]):
        x=24+col*290;d.text((x,460),name.replace('protector_','').replace('_',' '),font=font,fill='white')
        im=previews[name];large=im.resize((im.width*6,im.height*6),Image.Resampling.NEAREST);board.paste(large,(x,500),large)
        board.paste(im,(x+150,620),im)
    d.text((24,706),'Size comparison — actual vanilla Link pixels beside native actor candidates, all enlarged 6x',font=font,fill='white')
    link=Image.open(args.link_reference).convert('RGBA');bg=link.getpixel((0,0));link=link.crop((0,0,24,28))
    for y in range(link.height):
        for x in range(link.width):
            if link.getpixel((x,y))==bg:link.putpixel((x,y),(0,0,0,0))
    box=link.getbbox();assert box;link=link.crop(box);link.save(out/'vanilla-link-reference.png')
    for x,label,im in ((24,'Link',link),(240,'River protector',previews['protector_idle_front']),
                       (500,'Pirate warden',previews['warden_idle_front'])):
        d.text((x,748),label,font=small,fill='white')
        large=im.resize((im.width*6,im.height*6),Image.Resampling.NEAREST)
        board.paste(large,(x,1020-large.height),large)
    d.text((800,800),'First key poses; not a complete animation set.',font=small,fill='#c3d0c8')
    d.text((800,832),'Brace/charge: one-pixel torso shifts.',font=small,fill='#c3d0c8')
    d.text((800,864),'Healing currently reuses the idle pose.',font=small,fill='#c3d0c8')
    d.text((24,1040),f'{cursor} / {len(cells)} available OBJ cells; Baby and Princess slots preserved. Packed colour reconstruction PASS.',font=small,fill='#c3d0c8')
    d.text((24,1070),'Native art preview only. Combat motion, damage, palette coexistence and rescue runtime are not qualified.',font=small,fill='#c3d0c8')
    board.save(out/'actors-native-preview.png')
    report=dict(status='NATIVE_ART_PREVIEW_ONLY',concept_sha256=CONCEPT_SHA,base_sha256=BASE_SHA,link_reference_sha256=LINK_SHA,
                protector_sources={n:hashlib.sha256((args.protector/(n+'-roles.txt')).read_bytes()).hexdigest() for n in ('front','side')},
                pose_derivation={'warden_brace':'front torso lowered one pixel','warden_charge':'side torso moved left one pixel',
                                 'warden_vent':'front torso lowered one pixel plus five steam pixels',
                                 'protector_rest':'front head lowered one pixel','protector_healing':'reuses idle front'},
                palette_rows_assigned=False,global_sheets_assigned=False,rom_written=False,
                palettes={n:[f'{w:04X}' for w in p] for n,p in PALETTES.items()},frames=frame_data,sheets=sheet_report,
                unique_obj_cells=cursor,capacity=len(cells),reserved_cells=sorted(RESERVED),
                princess_cells_exact=True,baby_cells_reserved=True,all_compositions_exact=True,
                native_runtime_qualified=False)
    if args.emit_binding:emit_binding(out,report)
    (out/'RECEIPT.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps({k:report[k] for k in ('status','unique_obj_cells','capacity','princess_cells_exact','baby_cells_reserved','all_compositions_exact','rom_written')},indent=2))

if __name__=='__main__':main()
