#!/usr/bin/env python3
"""Generate native attract pose tables from the accepted indexed cast recipe."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]


def generate():
    source = json.loads((ROOT / 'Dungeons/Data/attract_royal_cast.json').read_text())
    payload = (ROOT / 'Dungeons/Data/attract_royal.4bpp').read_bytes()
    assert len(payload) == 8192
    assert hashlib.sha256(payload).hexdigest() == source['actorWindowSha256']
    names = list(source['poses'])
    lines = ['; Generated by Scripts/Generate/generate_attract_cast.py.',
             '; Bank $0C; helper $0CF9B5 consumes arrays with Y descending.']
    for name, pose in source['poses'].items():
        ox, oy = pose['origin']
        pieces = sorted(pose['pieces'], key=lambda p: -p['oam'])
        arrays = {
            'x': [(ox + p['x'] - 24) & 255 for p in pieces],
            'y': [(oy + p['y'] - 32) & 255 for p in pieces],
            'char': [p['char'] for p in pieces],
            'prop': [0x30 | p['palette'] << 1 | (p['sheet'] != '0A') | p['flip'] for p in pieces],
            'size': [2 if p['size'] == 16 else 0 for p in pieces],
        }
        lines.append('')
        for key, values in arrays.items():
            lines.append('AttractRoyal_' + name + '_' + key + ': db ' + ','.join('$%02X' % v for v in values))
    for key in ('x', 'y', 'char', 'prop', 'size'):
        lines += ['', 'AttractRoyal_Pose_' + key + ':',
                  '  dw ' + ','.join('AttractRoyal_' + n + '_' + key for n in names)]
    lines += ['', 'AttractRoyal_PoseCounts:',
              '  db ' + ','.join('$%02X,$00' % len(source['poses'][n]['pieces']) for n in names)]
    for scene in source['scenes']:
        cx, cy, _, _ = scene['camera']
        # Lowest OAM indices win: submit front actors, then all shadows.
        actors = sorted(scene['actors'], key=lambda a: -a[2])
        records = actors + [['ground_shadow', x, y] for name, x, y in actors if name != 'king']
        assert sum(len(source['poses'][name]['pieces']) for name, _, _ in records) <= 64
        values = [len(records)]
        for name, x, y in records:
            assert 0 <= x-cx < 256 and 0 <= y-cy < 224
            values += [names.index(name), x-cx, y-cy]
        lines += ['', 'AttractRoyal_Cast_' + scene['id'] + ':',
                  '  db ' + ','.join('$%02X' % v for v in values)]
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'Dungeons/Data/attract_royal_poses.asm'
    text = generate()
    if args.check:
        assert target.read_text() == text, 'Regenerate attract_royal_poses.asm'
    else:
        target.write_text(text)
    print('Attract royal cast: 11 native poses, 3 cards, 8192-byte actor window verified')


if __name__ == '__main__':
    main()
