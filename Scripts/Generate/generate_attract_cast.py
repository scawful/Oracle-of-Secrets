#!/usr/bin/env python3
"""Generate native attract pose, cast, and track tables from the cast recipe."""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[2]

FLAG_BITS = {
    'pose_on_start': 0x01,
    'blink_out': 0x02,
    'blink_in': 0x04,
    'hide': 0x08,
    'flip_h': 0x10,
}


def parse_u16(val):
    if isinstance(val, int):
        res = val
    elif isinstance(val, str):
        s = val.strip()
        res = int(s[1:], 16) if s.startswith('$') else int(s, 0)
    else:
        raise ValueError(f'Invalid u16 value: {val!r}')
    if not (0 <= res <= 0xFFFF):
        raise ValueError(f'u16 out of range: {val!r}')
    return res


def resolve_actor(ref, actor_entries):
    """Resolve an actor reference (int index in scene['actors'] or string id/unique pose)."""
    if isinstance(ref, bool):
        raise ValueError(f'Invalid actor reference: {ref!r}')
    if isinstance(ref, int):
        if not (0 <= ref < len(actor_entries)):
            raise ValueError(f'Actor index out of range: {ref}')
        return actor_entries[ref]
    if isinstance(ref, str):
        by_id = [a for a in actor_entries if a['id'] == ref]
        if len(by_id) == 1:
            return by_id[0]
        if len(by_id) > 1:
            raise ValueError(f'Ambiguous actor id: {ref!r}')
        by_pose = [a for a in actor_entries if a['pose'] == ref]
        if len(by_pose) == 1:
            return by_pose[0]
        if len(by_pose) > 1:
            raise ValueError(f'Ambiguous actor pose reference {ref!r}; assign explicit actor id')
        raise ValueError(f'Missing actor reference: {ref!r}')
    raise ValueError(f'Invalid actor reference type: {ref!r}')


def choose_shift(t_start, t_end, dx, dy, explicit_shift):
    if explicit_shift is not None:
        if not isinstance(explicit_shift, int) or not (0 <= explicit_shift <= 7 or explicit_shift == 0xFF):
            raise ValueError(f'Invalid track shift: {explicit_shift!r}')
        return explicit_shift
    duration = t_start - t_end
    mag = max(abs(dx), abs(dy))
    if duration == 0 or mag == 0:
        return 0
    for k in range(8):
        if (mag << k) == duration and (abs(dx) in (0, mag)) and (abs(dy) in (0, mag)):
            return k
    return 0xFF


def generate(source=None):
    if source is None:
        source = json.loads((ROOT / 'Dungeons/Data/attract_royal_cast.json').read_text())
    payload = (ROOT / 'Dungeons/Data/attract_royal.4bpp').read_bytes()
    assert len(payload) == 8192
    assert hashlib.sha256(payload).hexdigest() == source['actorWindowSha256']
    names = list(source['poses'])
    lines = ['; Generated by Scripts/Generate/generate_attract_cast.py.',
             '; Bank $58; AttractRoyal_DrawPoseLong consumes arrays with Y descending.']
    for name, pose in source['poses'].items():
        ox, oy = pose['origin']
        pieces = sorted(pose['pieces'], key=lambda p: -p['oam'])
        arrays = {
            'x': [(ox + p['x'] - 24) & 255 for p in pieces],
            'y': [(oy + p['y'] - 32) & 255 for p in pieces],
            'char': [p['char'] for p in pieces],
            'prop': [0x30 | p['palette'] << 1 | (p['sheet'] != '0A') | p['flip'] for p in pieces],
            'size': [2 if p['size'] == 16 else 0 for p in pieces],
        }
        lines.append('')
        for key, values in arrays.items():
            lines.append('AttractRoyal_' + name + '_' + key + ': db ' + ','.join('$%02X' % v for v in values))
    for key in ('x', 'y', 'char', 'prop', 'size'):
        lines += ['', 'AttractRoyal_Pose_' + key + ':',
                  '  dl ' + ','.join('AttractRoyal_' + n + '_' + key for n in names)]
    lines += ['', 'AttractRoyal_PoseCounts:',
              '  db ' + ','.join('$%02X' % len(source['poses'][n]['pieces']) for n in names)]

    scene_ids = []
    for scene in source['scenes']:
        scene_id = scene['id']
        scene_ids.append(scene_id)
        cx, cy, _, _ = scene['camera']
        orig_entries = []
        for idx, raw_actor in enumerate(scene['actors']):
            if len(raw_actor) == 3:
                pose_name, ax, ay = raw_actor
                actor_id = None
            elif len(raw_actor) == 4:
                pose_name, ax, ay, actor_id = raw_actor
            else:
                raise ValueError(f'Scene {scene_id} actor #{idx} must have 3 or 4 items')
            if pose_name not in source['poses']:
                raise ValueError(f'Scene {scene_id} actor #{idx} references missing pose {pose_name!r}')
            orig_entries.append({'orig_idx': idx, 'pose': pose_name, 'x': ax, 'y': ay, 'id': actor_id})

        # Lowest OAM indices win: submit front actors (highest Y), then all shadows.
        sorted_actors = sorted(orig_entries, key=lambda a: -a['y'])
        records = []
        for rec_idx, entry in enumerate(sorted_actors):
            entry['record_idx'] = rec_idx
            entry['shadow_idx'] = None
            records.append((entry['pose'], entry['x'], entry['y']))
        for entry in sorted_actors:
            if entry['pose'] != 'king':
                entry['shadow_idx'] = len(records)
                records.append(('ground_shadow', entry['x'], entry['y']))

        assert sum(len(source['poses'][name]['pieces']) for name, _, _ in records) <= 64, \
            f'Scene {scene_id} exceeds 64 OAM pieces'
        values = [len(records)]
        for name, x, y in records:
            assert 0 <= x - cx < 256 and 0 <= y - cy < 224, f'Scene {scene_id} actor out of view: {(name, x, y)}'
            values += [names.index(name), x - cx, y - cy]
        lines += ['', 'AttractRoyal_Cast_' + scene_id + ':',
                  '  db ' + ','.join('$%02X' % v for v in values)]

        tracks = scene.get('tracks')
        if not isinstance(tracks, list):
            raise ValueError(f'Scene {scene_id} missing tracks list')
        track_lines = []
        for t_idx, trk in enumerate(tracks):
            if not isinstance(trk, dict):
                raise ValueError(f'Scene {scene_id} track #{t_idx} must be an object')
            entry = resolve_actor(trk['actor'], orig_entries)
            t_start = parse_u16(trk['t_start'])
            t_end = parse_u16(trk['t_end'])
            if t_end > t_start:
                raise ValueError(f'Scene {scene_id} track #{t_idx}: t_end ({t_end:#x}) > t_start ({t_start:#x})')
            dx = int(trk.get('dx', 0))
            dy = int(trk.get('dy', 0))
            if not (-128 <= dx <= 127 and -128 <= dy <= 127):
                raise ValueError(f'Scene {scene_id} track #{t_idx}: dx/dy out of signed byte range')
            pose_end = trk.get('pose_end')
            if pose_end is not None:
                if pose_end not in source['poses']:
                    raise ValueError(f'Scene {scene_id} track #{t_idx}: missing pose {pose_end!r}')
                pose_byte = names.index(pose_end)
            else:
                pose_byte = 0xFF
            flag_mask = 0
            for flag_name in trk.get('flags', []):
                if flag_name not in FLAG_BITS:
                    raise ValueError(f'Scene {scene_id} track #{t_idx}: unknown flag {flag_name!r}')
                flag_mask |= FLAG_BITS[flag_name]
            shift_byte = choose_shift(t_start, t_end, dx, dy, trk.get('shift'))
            include_shadow = trk.get('shadow')
            if include_shadow is None:
                include_shadow = entry['shadow_idx'] is not None
            elif include_shadow and entry['shadow_idx'] is None:
                raise ValueError(f'Scene {scene_id} track #{t_idx}: actor {entry["pose"]!r} has no shadow')

            targets = [(entry['record_idx'], pose_byte, flag_mask)]
            if include_shadow and entry['shadow_idx'] is not None:
                shadow_flags = flag_mask & ~FLAG_BITS['flip_h']
                targets.append((entry['shadow_idx'], 0xFF, shadow_flags))

            for rec_id, p_byte, f_byte in targets:
                if dx == 0 and dy == 0 and p_byte == 0xFF and (f_byte & ~FLAG_BITS['pose_on_start']) == 0:
                    continue
                row = [rec_id, t_start & 0xFF, (t_start >> 8) & 0xFF, t_end & 0xFF, (t_end >> 8) & 0xFF,
                       dx & 0xFF, dy & 0xFF, p_byte, f_byte, shift_byte]
                track_lines.append('  db ' + ','.join('$%02X' % b for b in row))
        track_lines.append('  db $FF')
        lines += ['', 'AttractRoyal_Tracks_' + scene_id + ':'] + track_lines

    lines += ['', 'AttractRoyal_CastPointers:',
              '  dw ' + ','.join('AttractRoyal_Cast_' + sid for sid in scene_ids),
              '', 'AttractRoyal_TrackPointers:',
              '  dw ' + ','.join('AttractRoyal_Tracks_' + sid for sid in scene_ids)]
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'Dungeons/Data/attract_royal_poses.asm'
    text = generate()
    if args.check:
        assert target.read_text() == text, 'Regenerate attract_royal_poses.asm'
    else:
        target.write_text(text)
    source = json.loads((ROOT / 'Dungeons/Data/attract_royal_cast.json').read_text())
    print(f"Attract royal cast: {len(source['poses'])} poses, {len(source['scenes'])} cards, 8192-byte actor window verified")


if __name__ == '__main__':
    main()
