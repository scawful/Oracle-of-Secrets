#!/usr/bin/env python3
"""Generate Core/credits_text.asm: Oracle's names in the staff-roll credits.

Source list: Docs/oracle.org "** Credits" (copied verbatim into CREDITS below).

Vanilla text format (usdasm bank_0E.asm, pool CreditsTextLine):
  - pointers $0EB93D: 394 words, one per 8px row, offsets into data $0EB178.
  - line: db column, (chars*2)-1, then one character index per char.
  - offset $0014 is a single $FF byte = blank row.
  - rows 322-393 are the QUEST HISTORY stats (data offsets $057D+); this
    script leaves those rows, their data and the stats tables untouched.
Character indexes (Credits_CharacterToTile $0EB038):
  small A-Z: $00/$1A/$38 + n (three palettes); big top: A-Z $5D+n, 0-9 $53+n,
  "'" $77; big bottom: A-Z $83+n, 0-9 $79+n, "'" $9D; blank $9F.
The big font has no lowercase, "_" or "*"; DISPLAY maps those names.

Usage: python3 Scripts/Generate/generate_credits_text.py [--print]
"""

from __future__ import annotations

import argparse
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "Core" / "credits_text.asm"

# Docs/oracle.org "** Credits", verbatim.
CREDITS = [
    ("Zarby89", ["ZScream", "Code", "Graphics"]),
    ("Jared Brian", ["Shrine of Power", "ZScream", "Code"]),
    ("Jeimuzu", ["Shrine of Wisdom", "Tail Palace"]),
    ("Letterbomb", ["Shrine of Courage", "Music", "Graphics"]),
    ("NEONswift", ["Legends of Hyrule Maps"]),
    ("SePH", ["Overworld", "Graphics"]),
    ("Ghillie", ["Overworld", "Graphics"]),
    ("DarkLink45", ["Deku Link GFX"]),
    ("W*E*R*D*N*A", ["Graphics"]),
    ("GameyFireBro", ["Graphics"]),
]
BETA_ROLE = "Beta Testing"
BETA_TESTERS = [
    "Fruttielicious",
    "LEGO_Vince",
    "Spacewiki",
    "Evolvingfetus",
    "Discodragn",
    "BIGLOU",
    "HonorThyFamily",
]

# Names the big font cannot draw as written.
DISPLAY = {
    "LEGO_Vince": "LEGO VINCE",
    "W*E*R*D*N*A": "W E R D N A",
}

ROWS = 322            # rows 0..321; 322+ are the stats section
GAP = 22              # blank rows between blocks
BLANK_OFFSET = 0x0014
DATA_START = 0x0015   # leave vanilla offsets $0000-$0014 in place
DATA_LIMIT = 0x057D   # first stats-row data offset
SMALL_PALETTES = (0x38, 0x1A, 0x00)


def big(text: str, bottom: bool) -> list[int]:
    out = []
    for c in text:
        if c == " ":
            out.append(0x9F)
        elif "A" <= c <= "Z":
            out.append((0x83 if bottom else 0x5D) + ord(c) - 65)
        elif "0" <= c <= "9":
            out.append((0x79 if bottom else 0x53) + ord(c) - 48)
        elif c == "'":
            out.append(0x9D if bottom else 0x77)
        else:
            raise ValueError(f"big font cannot draw {c!r} in {text!r}")
    return out


def small(text: str, palette: int) -> list[int]:
    out = []
    for c in text:
        if c == " ":
            out.append(0x9F)
        elif "A" <= c <= "Z":
            out.append(palette + ord(c) - 65)
        else:
            raise ValueError(f"small font cannot draw {c!r} in {text!r}")
    return out


def name_text(name: str) -> str:
    return DISPLAY.get(name, name).upper()


def build_rows() -> list[tuple[str, list[int]] | None]:
    """One entry per row: None = blank, else (comment, char indexes)."""
    rows: list[tuple[str, list[int]] | None] = []

    def gap(n: int) -> None:
        rows.extend([None] * n)

    def name(n: str) -> None:
        t = name_text(n)
        rows.append((t, big(t, False)))
        rows.append((t, big(t, True)))

    for i, (who, roles) in enumerate(CREDITS):
        pal = SMALL_PALETTES[i % 3]
        for role in roles:
            rows.append((role.upper(), small(role.upper(), pal)))
        gap(2)
        name(who)
        gap(GAP)
    pal = SMALL_PALETTES[len(CREDITS) % 3]
    rows.append((BETA_ROLE.upper(), small(BETA_ROLE.upper(), pal)))
    gap(2)
    for j, who in enumerate(BETA_TESTERS):
        if j:
            gap(2)
        name(who)
    if len(rows) > ROWS:
        raise SystemExit(f"{len(rows)} rows > {ROWS}; lower GAP")
    gap(ROWS - len(rows))
    return rows


def emit(rows) -> str:
    out = [
        "; Generated by Scripts/Generate/generate_credits_text.py; edit the script, not this file.",
        "; Staff-roll rows 0-321 (Oracle credits from Docs/oracle.org). Rows 322-393",
        "; (QUEST HISTORY stats), their data at offsets $057D+ and the blank at $0014",
        "; stay vanilla.",
        "",
        "pushpc",
        "",
        f"org $0EB178+${DATA_START:04X}",
    ]
    ptrs = []
    seen: dict[tuple[int, ...], int] = {}
    off = DATA_START
    for row in rows:
        if row is None:
            ptrs.append((BLANK_OFFSET, ""))
            continue
        text, chars = row
        key = tuple(chars)
        if key not in seen:
            col = (32 - len(chars)) // 2
            body = [col, len(chars) * 2 - 1] + chars
            seen[key] = off
            out.append(f"  db {', '.join(f'${b:02X}' for b in body)} ; ${off:04X} {text}")
            off += len(body)
        ptrs.append((seen[key], text))
    if off > DATA_LIMIT:
        raise SystemExit(f"data ends at ${off:04X} > ${DATA_LIMIT:04X}")
    out += [
        f"warnpc $0EB178+${DATA_LIMIT:04X}",
        "",
        "org $0EB93D ; CreditsTextLine_pointers, rows 0-321",
    ]
    for i, (p, text) in enumerate(ptrs):
        out.append(f"  dw ${p:04X} ; row {i}{' ' + text if text else ''}")
    out += ["warnpc $0EB93D+(322*2)", "", "pullpc", ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--print", action="store_true", help="print the roll as it will read")
    args = ap.parse_args()
    rows = build_rows()
    if args.print:
        for i, row in enumerate(rows):
            if row is not None and (i == 0 or rows[i - 1] is None or rows[i - 1][0] != row[0]):
                print(f"{i:3d}  {row[0]}")
        return
    OUT.write_text(emit(rows))
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
