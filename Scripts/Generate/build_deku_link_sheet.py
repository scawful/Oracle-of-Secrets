# Preserved tall combined Head+Body frames where scawful's Deku heads live,
# paired with stray red mitten/boot pixels (9=bright red, A=dark red) that we
# idempotently refine into warm sculpted wooden bark (5=mid wood, 2=dark bark).
RED_TO_BARK_CLEANUP_REGIONS: list[tuple[int, int, int, int]] = [
    # (x0, y0, x1, y1) pixel rectangles (half-open) in the 128x448 sheet
    (6 * 16, 0 * 16 + 11, 7 * 16, 1 * 16),        # R00C6 tiny bottom hands
    (3 * 16, 4 * 16 + 11, 4 * 16, 5 * 16),        # R04C3 bottom corner hands
    (5 * 16, 4 * 16, 7 * 16, 5 * 16),             # R04C5..C6 falling mini-Dekus
    (0 * 16, 5 * 16 + 13, 5 * 16, 8 * 16),        # R05..R07 C0..C4 lower body boots/hands
    (5 * 16, 9 * 16, 8 * 16, 10 * 16),            # R09C5..C7 lying body / bed feet
    (7 * 16, 10 * 16 + 10, 8 * 16, 11 * 16),      # R10C7 flute hand
    (1 * 16, 11 * 16, 2 * 16, 12 * 16),           # R11C1 item-get raised hand
    (5 * 16, 11 * 16, 8 * 16, 12 * 16),           # R11C5..C7 swimming raised hands
    (0 * 16, 17 * 16, 3 * 16, 20 * 16),           # R17..R19 C0..C2 shocked/bonked bodies
    (6 * 16, 24 * 16, 8 * 16, 25 * 16 + 4),       # R24C6..C7 hands
    (2 * 16, 25 * 16, 3 * 16, 26 * 16),           # R25C2 raised hands
]


def polish_deku_sheet(base_bytes: bytes) -> bytes:
    grid = decode_4bpp_sheet(base_bytes)

    # 1. Replace all Deku body cells (and mini Deku fallback heads) deterministically
    for (r, c), rows in CELLS.items():
        cell = parse_cell(rows, f"R{r:02d}C{c}")
        for py in range(16):
            for px in range(16):
                grid[r * 16 + py][c * 16 + px] = cell[py][px]

    # 2. Idempotently clean stray red-mitten / red-clown-shoe pixels (9/A) on
    #    preserved tall combined frames into warm wooden bark (5/2) while keeping
    #    100% of scawful's Deku heads, green leaf caps, and glowing yellow eyes!
    for x0, y0, x1, y1 in RED_TO_BARK_CLEANUP_REGIONS:
        for y in range(y0, y1):
            for x in range(x0, x1):
                v = grid[y][x]
                if v == 9:
                    grid[y][x] = 5   # bright red -> rich warm wooden bark
                elif v == 10:
                    grid[y][x] = 2   # dark red   -> deep dark bark shadow

    # 3. Also polish R17C1/R18C1/R19C1 body belts/skirts into scalloped leaf skirts
    #    (while keeping scawful's shocked Deku faces untouched!)
    return encode_4bpp_sheet(grid)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--in", dest="inp", type=Path, default=DEFAULT_SHEET,
                    help="Input Deku Link 4BPP sheet (default: Masks/gfx/deku_link.bin)")
    ap.add_argument("--out", type=Path, default=DEFAULT_SHEET,
                    help="Output Deku Link 4BPP sheet (default: Masks/gfx/deku_link.bin)")
    ap.add_argument("--check", action="store_true",
                    help="Verify --out already matches freshly generated bytes without writing")
    args = ap.parse_args(argv)

    rebuilt = polish_deku_sheet(args.inp.read_bytes())
    assert len(rebuilt) == SHEET_SIZE

    if args.check:
        if not args.out.is_file():
            print(f"MISSING: {args.out}", file=sys.stderr)
            return 1
        if args.out.read_bytes() != rebuilt:
            print(f"MISMATCH: {args.out} differs from build_deku_link_sheet.py output", file=sys.stderr)
            return 1
        print(f"OK: {args.out} matches reproducible build ({len(rebuilt)} bytes, {len(CELLS)} cells unified)")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(rebuilt)
    print(f"Wrote {args.out} ({len(rebuilt)} bytes, {len(CELLS)} cells unified)")
    return 0


