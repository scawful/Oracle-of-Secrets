ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SHEET = ROOT / "Masks/gfx/deku_link.bin"
SHEET_SIZE = 28_672  # 28 rows x 8 cols of 16x16 cells
HEX_MAP = {ch: i for i, ch in enumerate(".123456789ABCDEF")}


def decode_4bpp_sheet(data: bytes) -> list[list[int]]:
    if len(data) != SHEET_SIZE:
        raise ValueError(f"Expected {SHEET_SIZE} bytes for Deku 4BPP sheet, got {len(data)}")
    grid = [[0] * 128 for _ in range(448)]
    for tile in range(896):
        tx = (tile % 16) * 8
        ty = (tile // 16) * 8
        base = tile * 32
        for y in range(8):
            b0 = data[base + y * 2]
            b1 = data[base + y * 2 + 1]
            b2 = data[base + 16 + y * 2]
            b3 = data[base + 16 + y * 2 + 1]
            for x in range(8):
                sh = 7 - x
                grid[ty + y][tx + x] = (
                    ((b0 >> sh) & 1)
                    | (((b1 >> sh) & 1) << 1)
                    | (((b2 >> sh) & 1) << 2)
                    | (((b3 >> sh) & 1) << 3)
                )
    return grid


def encode_4bpp_sheet(grid: list[list[int]]) -> bytes:
    out = bytearray(SHEET_SIZE)
    for tile in range(896):
        tx = (tile % 16) * 8
        ty = (tile // 16) * 8
        base = tile * 32
        for y in range(8):
            b0 = b1 = b2 = b3 = 0
            for x in range(8):
                val = grid[ty + y][tx + x]
                if val == 15:
                    raise ValueError(f"Forbidden color index 15 at ({tx + x}, {ty + y})")
                bit = 1 << (7 - x)
                if val & 1:
                    b0 |= bit
                if val & 2:
                    b1 |= bit
                if val & 4:
                    b2 |= bit
                if val & 8:
                    b3 |= bit
            out[base + y * 2] = b0
            out[base + y * 2 + 1] = b1
            out[base + 16 + y * 2] = b2
            out[base + 16 + y * 2 + 1] = b3
    return bytes(out)


def parse_cell(rows: list[str], name: str) -> list[list[int]]:
    if len(rows) != 16:
        raise ValueError(f"Cell {name}: expected 16 rows, got {len(rows)}")
    out = []
    for y, line in enumerate(rows):
        if len(line) != 16:
            raise ValueError(f"Cell {name} row {y}: expected 16 chars, got {len(line)}")
        out.append([HEX_MAP[ch] for ch in line])
    return out


