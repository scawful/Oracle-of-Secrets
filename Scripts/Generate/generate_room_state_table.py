#!/usr/bin/env python3
"""Generate RoomStateMode (Dungeons/generated/room_state_table.asm) from Data/room_state.json.

One byte per room $000-$127: bits 0-3 mode (0 none, 1 code_owned,
2 shutters_stay_open), bit 4 clear tag $AE, bit 5 clear tag $AF.
Runtime consumer: Dungeons/room_state.asm. --check compares without writing.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOM_COUNT = 0x128
MODES = {"none": 0, "code_owned": 1, "shutters_stay_open": 2}
TAG_BITS = {"AE": 0x10, "AF": 0x20}
HEADER = ("; Generated by Scripts/Generate/generate_room_state_table.py from\n"
          "; Data/room_state.json. Do not edit by hand.\n")


def parse_room(value) -> int:
    if isinstance(value, int) and not isinstance(value, bool):
        room = value
    elif isinstance(value, str):
        room = int(value, 16)
    else:
        raise ValueError(f"room must be an int or hex string, got {value!r}")
    if not 0 <= room < ROOM_COUNT:
        raise ValueError(f"room 0x{room:03X} is outside 0x000-0x127")
    return room


def build_table(data: dict) -> bytes:
    if data.get("schema_version") != 1:
        raise ValueError("schema_version must be 1")
    table = bytearray(ROOM_COUNT)
    seen = set()
    for entry in data.get("rooms", []):
        room = parse_room(entry.get("room"))
        if room in seen:
            raise ValueError(f"room 0x{room:03X} is listed twice")
        seen.add(room)
        mode = entry.get("mode")
        if mode not in MODES:
            raise ValueError(f"room 0x{room:03X}: unknown mode {mode!r}")
        value = MODES[mode]
        tags = entry.get("clear_tags", [])
        if tags and mode != "shutters_stay_open":
            raise ValueError(f"room 0x{room:03X}: clear_tags needs mode shutters_stay_open")
        for tag in tags:
            if tag not in TAG_BITS:
                raise ValueError(f"room 0x{room:03X}: unknown tag slot {tag!r} (use AE or AF)")
            value |= TAG_BITS[tag]
        table[room] = value
    return bytes(table)


def render(table: bytes) -> str:
    lines = [HEADER, "RoomStateMode:"]
    for start in range(0, len(table), 16):
        row = ", ".join(f"${b:02X}" for b in table[start:start + 16])
        lines.append(f"  db {row} ; ${start:03X}")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    root = Path(__file__).resolve().parents[2]
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--input", type=Path, default=root / "Data/room_state.json")
    p.add_argument("--out-asm", type=Path, default=root / "Dungeons/generated/room_state_table.asm")
    p.add_argument("--check", action="store_true", help="fail if the output is stale; write nothing")
    args = p.parse_args(argv)
    try:
        text = render(build_table(json.loads(args.input.read_text())))
    except (OSError, ValueError, json.JSONDecodeError) as e:
        print(f"room_state: {e}", file=sys.stderr)
        return 1
    if args.check:
        current = args.out_asm.read_text() if args.out_asm.exists() else None
        if current != text:
            print(f"room_state: {args.out_asm} is stale; run without --check", file=sys.stderr)
            return 1
        print("room_state: table up to date")
        return 0
    args.out_asm.write_text(text)
    print(f"room_state: wrote {args.out_asm}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
