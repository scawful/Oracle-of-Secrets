"""Fixture registry: SRAM saves by name, with sha256 and file slot.

SRAM files stay outside git (personal saves, regenerated by their own scripts);
fixtures.json records where each lives and its hash. A run refuses an SRAM
whose hash does not match the registry.
"""
from __future__ import annotations

import hashlib
import json
import os
from dataclasses import dataclass
from pathlib import Path

REGISTRY = Path(__file__).with_name('fixtures.json')


@dataclass(frozen=True)
class Fixture:
    name: str
    path: Path
    sha256: str
    file_slot: int
    contains: str

    def verify(self) -> None:
        if not self.path.is_file():
            raise FileNotFoundError(f'fixture {self.name}: {self.path} not found')
        got = sha256(self.path)
        if got != self.sha256:
            raise ValueError(f'fixture {self.name}: {self.path} sha256 {got} != registry {self.sha256}')


def sha256(path: Path) -> str:
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load_registry(path: Path = REGISTRY) -> dict[str, Fixture]:
    data = json.loads(Path(path).read_text())
    out = {}
    for name, entry in data.items():
        missing = {'path', 'sha256', 'file_slot', 'contains'} - set(entry)
        if missing:
            raise ValueError(f'fixture {name}: missing {sorted(missing)}')
        slot = entry['file_slot']
        if slot not in (1, 2, 3):
            raise ValueError(f'fixture {name}: file_slot {slot} not in 1-3')
        out[name] = Fixture(name, Path(os.path.expanduser(entry['path'])), entry['sha256'].lower(),
                            slot, entry['contains'])
    return out


def load_fixture(name: str, srm: str | Path | None = None, registry: Path = REGISTRY) -> Fixture:
    """Registry entry `name`, verified. `srm` points at another copy of the same file
    (same sha256), for machines where the registry path does not exist."""
    reg = load_registry(registry)
    if name not in reg:
        raise KeyError(f'fixture {name!r} not in {registry} (have: {", ".join(sorted(reg))})')
    fx = reg[name]
    if srm is not None:
        fx = Fixture(fx.name, Path(srm).expanduser(), fx.sha256, fx.file_slot, fx.contains)
    fx.verify()
    return fx
